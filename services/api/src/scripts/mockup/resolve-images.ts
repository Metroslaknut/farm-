/**
 * Developer tool: rebuilds `images.ts` from Wikimedia Commons (`pnpm --filter @farmplus/api seed:mockup:images`).
 * Every URL written is fetched first and kept only if it answers 200 with an image content type, so the seed never
 * stores a made-up link. Keys with no usable result are left out; the seed falls back to a placehold.co image.
 * Keys that already have images are kept unless `--all` is passed (Commons rate-limits, so runs resume where they stopped).
 */
import { writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { IMAGE_QUERIES, type ImageKey } from './image-queries';
import { IMAGES, type MockImage } from './images';

const PER_KEY = 4;
const USER_AGENT = 'FarmPlusMockupSeed/0.1 (development test data)';
/** Commons search also returns scans of old books, museum objects and dishes: not what a farm listing should show. */
const SKIP =
  /\b(map|diagram|logo|drawing|illustration|stamp|coat of arms|chart|sketch|painting|LACMA|Walters|catalogue|meal|chowder|recipe|museum)\b|\((1[5-9]\d\d)\)/i;

const sleep = (ms: number) => new Promise((resolve) => setTimeout(resolve, ms));

async function get(url: string): Promise<Response> {
  for (let attempt = 0; ; attempt++) {
    const res = await fetch(url, { headers: { 'User-Agent': USER_AGENT } });
    if (res.status !== 429 || attempt >= 5) return res;
    await res.arrayBuffer();
    await sleep(5_000 * (attempt + 1));
  }
}

interface CommonsPage {
  title: string;
  imageinfo?: { thumburl?: string; mime?: string; descriptionurl?: string }[];
}

async function lookup(params: Record<string, string>): Promise<CommonsPage[]> {
  const query = new URLSearchParams({
    action: 'query',
    prop: 'imageinfo',
    iiprop: 'url|mime',
    iiurlwidth: '640',
    format: 'json',
    ...params,
  });
  const res = await get(`https://commons.wikimedia.org/w/api.php?${query}`);
  if (!res.ok)
    throw new Error(`Commons lookup failed (${res.status}) for ${JSON.stringify(params)}`);
  const body = (await res.json()) as { query?: { pages?: Record<string, CommonsPage> } };
  return Object.values(body.query?.pages ?? {});
}

function toImage(p: CommonsPage): MockImage | null {
  const info = p.imageinfo?.[0];
  if (!info?.thumburl || !/^image\/(jpeg|png)$/.test(info.mime ?? '')) return null;
  // Drop Commons' tracking parameters: the thumbnail path alone is the stable address.
  return { url: info.thumburl.split('?')[0]!, title: p.title, page: info.descriptionurl ?? '' };
}

/** Free-text search: results are filtered, and should still be reviewed before they are committed. */
async function search(query: string): Promise<MockImage[]> {
  const pages = await lookup({
    generator: 'search',
    gsrsearch: `${query} filetype:bitmap`,
    gsrnamespace: '6',
    gsrlimit: '20',
  });
  return pages.flatMap((p) => (SKIP.test(p.title) ? [] : (toImage(p) ?? [])));
}

/** Hand-picked files, kept in the given order. */
async function files(titles: readonly string[]): Promise<MockImage[]> {
  if (titles.length === 0) return [];
  const pages = await lookup({ titles: titles.map((t) => `File:${t}`).join('|') });
  return titles.flatMap((t) => {
    const page = pages.find((p) => p.title.replace(/_/g, ' ') === `File:${t}`);
    const image = page && toImage(page);
    if (!image) console.warn(`  not found on Commons: ${t}`);
    return image ? [image] : [];
  });
}

async function reachable(url: string): Promise<boolean> {
  try {
    const res = await get(url);
    await res.arrayBuffer();
    return res.ok && (res.headers.get('content-type') ?? '').startsWith('image/');
  } catch {
    return false;
  }
}

async function save(out: Record<string, MockImage[]>): Promise<void> {
  const target = fileURLToPath(new URL('./images.ts', import.meta.url));
  await writeFile(
    target,
    `// Generated by resolve-images.ts. Images: Wikimedia Commons (see each \`page\` for author and licence).\n` +
      `export interface MockImage {\n  url: string;\n  title: string;\n  page: string;\n}\n\n` +
      `export const IMAGES: Record<string, MockImage[]> = ${JSON.stringify(out, null, 2)};\n`,
  );
}

async function main(): Promise<void> {
  const all = process.argv.includes('--all');
  const out: Record<string, MockImage[]> = all ? {} : { ...IMAGES };
  for (const [key, query] of Object.entries(IMAGE_QUERIES) as [
    ImageKey,
    string | readonly string[],
  ][]) {
    if ((out[key]?.length ?? 0) > 0) continue;
    const picked: MockImage[] = [];
    const candidates = typeof query === 'string' ? await search(query) : await files(query);
    for (const candidate of candidates) {
      if (picked.length >= PER_KEY) break;
      if (await reachable(candidate.url)) picked.push(candidate);
    }
    out[key] = picked;
    await save(out);
    console.log(`${key}: ${picked.length} image(s) ${picked.map((p) => p.title).join(' | ')}`);
    await sleep(1_500);
  }
  console.log('images.ts is up to date');
}

main().catch((error: unknown) => {
  console.error(error instanceof Error ? error.message : error);
  process.exit(1);
});
