// ─── Animal types and breeds ─────────────────────────────────────────────────────────────────────────────────────────

export interface BreedSpec {
  key: string;
  name: string;
  nameTh: string;
  /** Adult live weight (kg) by sex and weight at birth/hatch. */
  adultKg: { male: number; female: number };
  birthKg: number;
  /** Growth time constant (days) for w(t) = birth + (adult − birth)(1 − e^(−t/τ)). */
  tauDays: number;
  /** Youngest age at which an animal is used as a parent, and a plausible maximum age on a farm. */
  breedingAgeDays: number;
  maxAgeDays: number;
  colors: string[];
  /** Asking price for a listing: per kg live weight, or a flat price per head (baht). */
  price: { perKg: number } | { each: number };
}

export interface AnimalTypeSpec {
  key: string;
  name: string;
  nameTh: string;
  /** Animal code prefix on the farm, e.g. CTL-001. */
  codePrefix: string;
  /** Pets get names; flock/pond animals get a breed name and a number. */
  naming: 'pet' | 'livestock' | 'numbered';
  /** Weighing method recorded in growth history. */
  weighMethod: 'scale' | 'tape_estimate';
  breeds: BreedSpec[];
}

const breed = (
  key: string,
  name: string,
  nameTh: string,
  spec: Omit<BreedSpec, 'key' | 'name' | 'nameTh'>,
): BreedSpec => ({ key, name, nameTh, ...spec });

