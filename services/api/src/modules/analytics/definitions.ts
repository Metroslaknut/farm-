export const DEFINITION_BY_KEY = new Map(DEFINITIONS.map((d) => [d.key, d]));

/** Definitions for exactly the metrics a dashboard returned. Throws if one has no definition (a bug caught by tests). */
export function definitionsFor(
  scope: 'farm' | 'admin',
  sections: Record<string, { metrics: Record<string, unknown> } | undefined>,
): Record<string, MetricDefinition> {
  const out: Record<string, MetricDefinition> = {};
  for (const [section, data] of Object.entries(sections)) {
    for (const key of Object.keys(data?.metrics ?? {})) {
      const id = `${scope}.${section}.${key}`;
      const d = DEFINITION_BY_KEY.get(id);
      if (!d) throw new Error(`Metric ${id} has no definition`);
      out[id] = d;
    }
  }
  return out;
}
