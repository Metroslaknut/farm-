import type { MetricDefinition, MetricUnit } from '@farmplus/shared-types';

/**
 * THE metric catalogue. Every figure a dashboard returns is named here with what it means, how it is calculated, what is
 * counted and what is left out. The API returns the definitions of exactly the metrics it returned; a test fails if a
 * metric is returned without one.
 *
 * Money vocabulary used throughout (they are different things and are never mixed):
 *  - GROSS SALES       item price of orders that are paid and still standing (shipping excluded).
 *  - PLATFORM COMMISSION  the fee FARM+ keeps from those sales (frozen on each order at checkout).
 *  - NET PROCEEDS      gross sales − commission: what the seller side is owed from them (ESTIMATED: before shipping
 *                      costs, payment-provider fees, taxes and anything outside FARM+).
 *  - REVENUE           NOT used as a word here: for the seller it would be ambiguous (gross or net?) and for the platform it is the commission.
 *  - PROFIT            NOT calculated: FARM+ only knows costs that were recorded, so "net proceeds over recorded costs" is
 *                      shown instead and labelled indicative.
 */
const PAID_STANDING =
  'orders in status PAID, PROCESSING, SHIPPED or DELIVERED whose payment was confirmed (paidAt) inside the dates';
const NOT_STANDING =
  'orders that were cancelled before payment, and paid orders now REFUND_PENDING or REFUNDED (they are shown separately as excluded/refunded)';

function def(
  scope: 'farm' | 'admin',
  section: string,
  key: string,
  label: string,
  unit: MetricUnit,
  d: Omit<MetricDefinition, 'key' | 'scope' | 'section' | 'label' | 'unit'>,
): MetricDefinition {
  return { key: `${scope}.${section}.${key}`, scope, section, label, unit, ...d };
}
